import type { Campaign } from './campaign-model';
import type { Employee } from './employee-model';
import type { HRUser } from './hr-user-model';

export const ParticipantGCMLevelKeyToLabel = {
  'GCM7': 'GCM 7',
  'GCM8': 'GCM 8',
  'GCM9': 'GCM 9',
  'GCM10': 'GCM 10+'
} as const;
export type ParticipantGCMLevelKey = keyof typeof ParticipantGCMLevelKeyToLabel;

export const ParticipantLeadershipRoleKeyToLabel = {
  'BusinessUnitLeader': 'Business Unit Leader',
  'FunctionalLeader': 'Functional Leader',
  'RegionalLeader': 'Regional Leader',
  'EnterpriseLeader': 'Enterprise Leader'
} as const;
export type ParticipantLeadershipRoleKey = keyof typeof ParticipantLeadershipRoleKeyToLabel;

export const ParticipantStatusKeyToLabel = {
  'Invited': 'Invited',
  'InProgress': 'In Progress',
  'Submitted': 'Submitted',
  'Completed': 'Completed',
  'Withdrawn': 'Withdrawn'
} as const;
export type ParticipantStatusKey = keyof typeof ParticipantStatusKeyToLabel;

export interface Participant {
  /**
   * @displayName Participant ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Participant Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  participantName: string;
  /**
   * @displayName Campaign
   * @validationRule Required for create/update operations
   */
  campaign: Pick<Campaign, 'id' | 'campaignName'>;
  /**
   * @displayName Completed Date
   */
  completedDate?: string;
  /**
   * @displayName Employee
   * @validationRule Required for create/update operations
   */
  employee: Pick<Employee, 'id' | 'employeeName'>;
  /**
   * @displayName GCM Level
   * @validationRule Required for create/update operations
   */
  gCMLevelKey: ParticipantGCMLevelKey;
  /**
   * @displayName HR Contact
   * @validationRule Required for create/update operations
   */
  hRContact: Pick<HRUser, 'id' | 'hRUserName'>;
  /**
   * @displayName Invited Date
   * @validationRule Required for create/update operations
   */
  invitedDate: string;
  /**
   * @displayName Leadership Role
   * @validationRule Required for create/update operations
   */
  leadershipRoleKey: ParticipantLeadershipRoleKey;
  /**
   * @displayName Manager
   * @validationRule Required for create/update operations
   */
  manager: Pick<Employee, 'id' | 'employeeName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ParticipantStatusKey;
}

export const _Participant = 'Participant' as const;
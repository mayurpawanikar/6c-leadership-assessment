import type { HRUser } from './hr-user-model';

export const CampaignCampaignTypeKeyToLabel = {
  'KeyTalent': 'Key Talent',
  'EmergingLeaders': 'Emerging Leaders',
  'Promotion': 'Promotion',
  'Succession': 'Succession',
  'General': 'General'
} as const;
export type CampaignCampaignTypeKey = keyof typeof CampaignCampaignTypeKeyToLabel;

export const CampaignStatusKeyToLabel = {
  'Draft': 'Draft',
  'Open': 'Open',
  'Closed': 'Closed',
  'Archived': 'Archived'
} as const;
export type CampaignStatusKey = keyof typeof CampaignStatusKeyToLabel;

export interface Campaign {
  /**
   * @displayName Campaign ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Campaign Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  campaignName: string;
  /**
   * @displayName Archived Date
   */
  archivedDate?: string;
  /**
   * @displayName Campaign Type
   * @validationRule Required for create/update operations
   */
  campaignTypeKey: CampaignCampaignTypeKey;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Description
   */
  description?: string;
  /**
   * @displayName End Date
   * @validationRule Required for create/update operations
   */
  endDate: string;
  /**
   * @displayName Framework Version
   * @validationRule Required for create/update operations
   */
  frameworkVersion: string;
  /**
   * @displayName HR Contact
   * @validationRule Required for create/update operations
   */
  hRContact: Pick<HRUser, 'id' | 'hRUserName'>;
  /**
   * @displayName Start Date
   * @validationRule Required for create/update operations
   */
  startDate: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: CampaignStatusKey;
}

export const _Campaign = 'Campaign' as const;
import type { Assessment } from './assessment-model';
import type { FrameworkConfiguration } from './framework-configuration-model';

export const ResponseLockedFactorKeyToLabel = {
  'Capability': 'Capability',
  'Capacity': 'Capacity',
  'Character': 'Character',
  'CustomerCentricity': 'Customer Centricity',
  'CommercialAcumen': 'Commercial Acumen',
  'CulturalEquity': 'Cultural Equity'
} as const;
export type ResponseLockedFactorKey = keyof typeof ResponseLockedFactorKeyToLabel;

export interface Response {
  /**
   * @displayName Response ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Response Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  responseName: string;
  /**
   * @displayName Assessment
   * @validationRule Required for create/update operations
   */
  assessment: Pick<Assessment, 'id' | 'assessmentName'>;
  /**
   * @displayName Employee Comment
   */
  employeeComment?: string;
  /**
   * @displayName Employee Rating
   * @validationRule Required for create/update operations
   */
  employeeRating: number;
  /**
   * @displayName Framework Configuration
   * @validationRule Required for create/update operations
   */
  frameworkConfiguration: Pick<FrameworkConfiguration, 'id' | 'frameworkConfigurationName'>;
  /**
   * @displayName Locked Dimension
   * @validationRule Required for create/update operations
   */
  lockedDimension: string;
  /**
   * @displayName Locked Factor
   * @validationRule Required for create/update operations
   */
  lockedFactorKey: ResponseLockedFactorKey;
  /**
   * @displayName Locked Question Text
   * @validationRule Required for create/update operations
   */
  lockedQuestionText: string;
  /**
   * @displayName Manager Comment
   */
  managerComment?: string;
  /**
   * @displayName Manager Rating
   */
  managerRating?: number;
}

export const _Response = 'Response' as const;